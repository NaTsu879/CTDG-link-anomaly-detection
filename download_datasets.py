"""
Download datasets and generate synthetic anomalies for link anomaly detection, non-interactively.

The script:
    1. clones the TGB-link-anomaly-detection repository (if it is not present yet),
    2. downloads the datasets from Zenodo (Poursafaei et al., 2022) into `<dataset_root>/<name>/ml_<name>.{csv,npy}`,
       which is where `LinkAnomDetDataset` looks for them, so it never asks for an interactive download,
    3. generates the typed synthetic anomalies with `link_anomaly_generator.py` from TGB-link-anomaly-detection.

The TGB-link-anomaly-detection repository has no `__init__.py` files, so it is used by adding it to PYTHONPATH
instead of installing it. The training scripts must be run with the same PYTHONPATH, e.g.:

    python download_datasets.py --dataset_root /kaggle/working/DATASETS --datasets wikipedia uci
    PYTHONPATH=/kaggle/working/TGB-link-anomaly-detection python train_tgb_linkanomdet.py --config_path=...
"""

import argparse
import os
import os.path as osp
import shutil
import subprocess
import sys
import time
import zipfile

import requests

TGB_REPO_URL = "https://github.com/timpostuvan/TGB-link-anomaly-detection.git"
ZENODO_URL = "https://zenodo.org/records/7213796/files/{name}.zip"
ZENODO_DATASETS = [
    "wikipedia",
    "reddit",
    "mooc",
    "lastfm",
    "enron",
    "SocialEvo",
    "uci",
]
# Generated by TGB-link-anomaly-detection when the dataset is loaded for the first time.
GENERATED_DATASETS = ["synthetic"]
# Have to be downloaded and pre-processed manually with the scripts in TGB-link-anomaly-detection.
MANUAL_DATASETS = ["lanl", "darpa-theia", "darpa-trace"]
ANOMALY_TYPES = [
    "temporal-structural-contextual",
    "structural-contextual",
    "temporal-contextual",
    "temporal",
    "contextual",
]


def ensure_tgb_repo(tgb_dir: str) -> str:
    """
    Clone TGB-link-anomaly-detection into `tgb_dir` if it does not exist yet.
    """
    tgb_dir = osp.abspath(tgb_dir)
    if osp.isdir(osp.join(tgb_dir, "tgb", "linkanomdet")):
        print(f"INFO: TGB-link-anomaly-detection found at {tgb_dir}")
    else:
        print(f"INFO: Cloning TGB-link-anomaly-detection into {tgb_dir}")
        subprocess.run(
            ["git", "clone", "--depth", "1", TGB_REPO_URL, tgb_dir], check=True
        )
    return tgb_dir


def download_file(url: str, path: str, num_retries: int = 3) -> None:
    """
    Download a file with a progress indicator, retrying on network errors.
    """
    for attempt in range(1, num_retries + 1):
        try:
            with requests.get(url, stream=True, timeout=60) as response:
                response.raise_for_status()
                total_size = int(response.headers.get("content-length", 0))
                downloaded_size, last_report = 0, 0.0
                with open(path + ".part", "wb") as file:
                    for chunk in response.iter_content(chunk_size=1 << 20):
                        file.write(chunk)
                        downloaded_size += len(chunk)
                        if time.time() - last_report > 5:
                            last_report = time.time()
                            progress = (
                                f"{100 * downloaded_size / total_size:.0f}%"
                                if total_size
                                else f"{downloaded_size >> 20} MB"
                            )
                            print(f"INFO:   {osp.basename(path)}: {progress}")
            os.replace(path + ".part", path)
            return
        except requests.RequestException as error:
            print(f"WARNING: Download attempt {attempt} failed: {error}")
            if attempt == num_retries:
                raise
            time.sleep(5 * attempt)


def download_dataset(name: str, dataset_root: str) -> None:
    """
    Download a dataset from Zenodo into `<dataset_root>/<name>/ml_<name>.{csv,npy}`.
    """
    dataset_dir = osp.join(dataset_root, name.replace("-", "_"))
    target_files = [f"ml_{name}.csv", f"ml_{name}.npy"]
    if all(osp.exists(osp.join(dataset_dir, f)) for f in target_files):
        print(f"INFO: Dataset {name} already downloaded.")
        return

    os.makedirs(dataset_dir, exist_ok=True)
    zip_path = osp.join(dataset_dir, f"{name}.zip")
    print(f"INFO: Downloading dataset {name}")
    download_file(ZENODO_URL.format(name=name), zip_path)

    # The archive contains `<name>/ml_<name>.csv`, `<name>/ml_<name>.npy`, and `<name>/ml_<name>_node.npy`.
    with zipfile.ZipFile(zip_path, "r") as zip_file:
        members = {osp.basename(m): m for m in zip_file.namelist()}
        for target_file in target_files:
            if target_file not in members:
                raise FileNotFoundError(f"{target_file} not found in {zip_path}")
            with zip_file.open(members[target_file]) as source, open(
                osp.join(dataset_dir, target_file), "wb"
            ) as target:
                shutil.copyfileobj(source, target)
    os.remove(zip_path)
    print(f"INFO: Dataset {name} saved to {dataset_dir}")


def generate_anomalies(
    name: str,
    dataset_root: str,
    tgb_dir: str,
    anom_types: list,
    num_anom_sets: int,
    val_ratio: float,
    test_ratio: float,
    anom_prop: float,
    seed: int,
) -> None:
    """
    Generate typed synthetic anomalies with `link_anomaly_generator.py` from TGB-link-anomaly-detection.
    Already generated anomaly sets are skipped by the generator itself.
    """
    generator_script = osp.join(
        tgb_dir, "tgb", "datasets", "dataset_scripts", "link_anomaly_generator.py"
    )
    env = dict(os.environ)
    env["PYTHONPATH"] = os.pathsep.join(
        [tgb_dir] + ([env["PYTHONPATH"]] if env.get("PYTHONPATH") else [])
    )
    for anom_type in anom_types:
        print(f"INFO: Generating {anom_type} anomalies for {name}")
        subprocess.run(
            [
                sys.executable,
                generator_script,
                "--dataset_name",
                name,
                "--output_root",
                dataset_root,
                "--val_ratio",
                str(val_ratio),
                "--test_ratio",
                str(test_ratio),
                "--anom_type",
                anom_type,
                "--num_anom_sets",
                str(num_anom_sets),
                "--anom_prop",
                str(anom_prop),
                "--seed",
                str(seed),
            ],
            check=True,
            env=env,
            # The generator never asks for input because the dataset files already exist.
            stdin=subprocess.DEVNULL,
        )


def main():
    parser = argparse.ArgumentParser(
        "Download datasets and generate anomalies for link anomaly detection"
    )
    parser.add_argument(
        "--dataset_root",
        type=str,
        required=True,
        help="Where to save datasets and anomalies (same as `dataset_root` in the experiment config).",
    )
    parser.add_argument(
        "--datasets",
        type=str,
        nargs="+",
        default=["wikipedia"],
        choices=ZENODO_DATASETS + GENERATED_DATASETS + MANUAL_DATASETS,
        help="Datasets to prepare.",
    )
    parser.add_argument(
        "--anom_types",
        type=str,
        nargs="+",
        default=ANOMALY_TYPES,
        choices=ANOMALY_TYPES,
        help="Types of synthetic anomalies to generate.",
    )
    parser.add_argument(
        "--num_anom_sets",
        type=int,
        default=1,
        help="Number of anomaly sets per type (`num_anom_sets` in the experiment config).",
    )
    parser.add_argument(
        "--tgb_dir",
        type=str,
        default=osp.join(osp.dirname(osp.abspath(os.getcwd())), "TGB-link-anomaly-detection"),
        help="Where TGB-link-anomaly-detection is (or should be cloned).",
    )
    parser.add_argument("--val_ratio", type=float, default=0.15)
    parser.add_argument("--test_ratio", type=float, default=0.15)
    parser.add_argument(
        "--anom_prop", type=float, default=0.05, help="Proportion of injected anomalies."
    )
    parser.add_argument(
        "--seed", type=int, default=44, help="Seed of the anomaly generator."
    )
    parser.add_argument(
        "--skip_anomalies",
        action="store_true",
        help="Only download the datasets, without generating anomalies.",
    )
    args = parser.parse_args()

    dataset_root = osp.abspath(args.dataset_root)
    os.makedirs(dataset_root, exist_ok=True)
    tgb_dir = ensure_tgb_repo(args.tgb_dir)

    for name in args.datasets:
        if name in MANUAL_DATASETS:
            print(
                f"WARNING: {name} has organic anomalies and has to be downloaded and pre-processed manually "
                f"with the scripts in {osp.join(tgb_dir, 'tgb', 'datasets')}. Skipping."
            )
            continue
        if name in ZENODO_DATASETS:
            download_dataset(name, dataset_root)
        if not args.skip_anomalies:
            generate_anomalies(
                name=name,
                dataset_root=dataset_root,
                tgb_dir=tgb_dir,
                anom_types=args.anom_types,
                num_anom_sets=args.num_anom_sets,
                val_ratio=args.val_ratio,
                test_ratio=args.test_ratio,
                anom_prop=args.anom_prop,
                seed=args.seed,
            )

    print(f"INFO: Done. Run the training scripts with PYTHONPATH={tgb_dir}")


if __name__ == "__main__":
    main()
